#!/usr/bin/env python3
"""Generate all Harmony ColdFire assembly; --check refuses source drift."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=54455', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-jump-tables', '-fno-asynchronous-unwind-tables', '-fno-ident',
         '-fomit-frame-pointer', '-Wall', '-Wextra', '-Wmissing-prototypes',
         '-Wstrict-prototypes', '-Werror']
UNITS = ('size', 'core', 'packed', 'storage', 'events', 'ui', 'operations',
         'roots', 'recording', 'scenes', 'track-retention', 'accumulator')

def main():
    generated = {}
    with tempfile.TemporaryDirectory(prefix='harmony-generate-') as tmp:
        for unit in UNITS:
            dest = pathlib.Path(tmp)/f'{unit}.s'
            subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', '-o', str(dest), f'{unit}.c'],
                           cwd=HERE, check=True)
            generated[HERE/f'{unit}.s'] = f'| Generated by generate.py; edit {unit}.c and its headers.\n'+dest.read_text()
    # Do not publish a mixture of old and new units after a compiler failure.
    for target, body in generated.items():
        if '--check' in sys.argv:
            if not target.exists() or target.read_text()!=body:
                raise SystemExit(f'stale generated assembly: {target}')
        else:
            target.write_text(body)
    if '--check' in sys.argv:
        print('Harmony generated assembly matches')

if __name__ == '__main__':
    main()
