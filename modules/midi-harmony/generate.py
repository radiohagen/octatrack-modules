#!/usr/bin/env python3
"""Generate voicing assembly using the existing freestanding pattern."""
import pathlib
import subprocess
import sys
import tempfile
from degrees.generate import FLAGS

HERE = pathlib.Path(__file__).resolve().parent

def main():
    generated = {}
    with tempfile.TemporaryDirectory(prefix='harmony-generate-') as tmp:
        for unit in ('size',):
            dest = pathlib.Path(tmp)/f'{unit}.s'
            subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', '-o', str(dest), f'{unit}.c'],
                           cwd=HERE, check=True)
            generated[HERE/f'{unit}.s'] = f'| Generated by generate.py; edit {unit}.c / {unit}.h.\n'+dest.read_text()
    for target, body in generated.items():
        if '--check' in sys.argv:
            if not target.exists() or target.read_text()!=body:
                raise SystemExit(f'stale generated assembly: {target}')
        else:
            target.write_text(body)
    if '--check' in sys.argv:
        print('Harmony generated assembly matches')

if __name__ == '__main__':
    main()
