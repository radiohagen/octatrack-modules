/* Degree/register codec. Native NOTE bytes never contain this encoding.
 * code = 7 * (tonic_octave + 2) + zero_based_degree, 0..83.
 * The extra low octave admits C-1 as degree 2 above B-2, for example.
 * 0xff remains the unlocked sentinel. MIDI 60 is C4.
 * Scale ABI matches mh_scale_record: tonic<<2 | mode<<6; -1 = C major.
 * Encode snaps nearest, lower on ties. Decode returns -1 outside MIDI.
 * d0=value,d1=scale -> d0=result; all other registers preserved.
 */
    .text
    .global hd_encode,hd_decode,hd_format
    .global hd_encode_c,hd_decode_c
hd_encode_c:
    move.l 4(%sp),%d0
    move.l 8(%sp),%d1
    bra.w hd_encode
hd_decode_c:
    move.l 4(%sp),%d0
    move.l 8(%sp),%d1
    bra.w hd_decode
hd_decode:
    lea -12(%sp),%sp
    movem.l %d3/%d5/%a0,(%sp)
    cmpi.l #83,%d0
    bhi.s .decode_bad
    bsr.w .scale
    mulu.w #84,%d3
    add.l %d3,%d0
    lea hd_decode_pitch,%a0
    mvz.b (%a0,%d0.l),%d0
    add.l %d5,%d0
    subi.l #12,%d0
    cmpi.l #127,%d0
    bls.s .decode_done
.decode_bad:
    moveq #-1,%d0
.decode_done:
    movem.l (%sp),%d3/%d5/%a0
    lea 12(%sp),%sp
    rts

hd_encode:
    lea -12(%sp),%sp
    movem.l %d3/%d5/%a0,(%sp)
    cmpi.l #127,%d0
    bhi.s .encode_bad
    bsr.w .scale
    tst.l %d0
    beq.s .encode_minimum
    sub.l %d5,%d0
    addi.l #12,%d0 /* relative pitch+12, always 2..139 */
    mulu.w #140,%d3
    add.l %d3,%d0
    lea hd_encode_relative,%a0
    mvz.b (%a0,%d0.l),%d0
    bra.s .encode_done
.encode_minimum:
    /* All seven diatonic modes have gaps <=2 semitones. With lower-on-tie
     * snapping the only out-of-MIDI nearest pitch is -1 for input 0.
     * MIDI 0 therefore selects the first playable degree directly. */
    mulu.w #12,%d3
    add.l %d5,%d3
    lea hd_encode_minimum,%a0
    mvz.b (%a0,%d3.l),%d0
    bra.s .encode_done
.encode_bad:
    moveq #-1,%d0
.encode_done:
    movem.l (%sp),%d3/%d5/%a0
    lea 12(%sp),%sp
    rts

/* d1 -> d3 mode,d5 tonic. Invalid scale falls back to C major.
 * Low two scale bits are ignored, preserving the native codec ABI. */
.scale:
    moveq #0,%d3
    moveq #0,%d5
    tst.l %d1
    bmi.s .scale_done
    move.l %d1,%d3
    lsr.l #6,%d3
    cmpi.l #6,%d3
    bhi.s .scale_fallback
    move.l %d1,%d5
    lsr.l #2,%d5
    andi.l #15,%d5
    cmpi.l #11,%d5
    bls.s .scale_done
.scale_fallback:
    moveq #0,%d3
    moveq #0,%d5
.scale_done:
    rts

/* Native formatter (char *buffer, int code); no stock formatter needed. */
hd_format:
    lea -16(%sp),%sp
    movem.l %d2-%d3/%a0-%a1,(%sp)
    move.l 20(%sp),%a0
    move.l 24(%sp),%d0
    cmpi.l #83,%d0
    bhi.s .format_unlocked
    move.l %d0,%d1
    moveq #7,%d2
    divu.l %d2,%d0
    mulu.l %d0,%d2
    sub.l %d2,%d1
    addi.l #49,%d1
    move.b %d1,(%a0)+
    move.b #58,(%a0)+
    subq.l #2,%d0
    bpl.s .format_octave
    move.b #45,(%a0)+
    neg.l %d0
.format_octave:
    addi.l #48,%d0
    move.b %d0,(%a0)+
    clr.b (%a0)
    bra.s .format_done
.format_unlocked:
    move.b #45,(%a0)+
    move.b #45,(%a0)+
    clr.b (%a0)
.format_done:
    movem.l (%sp),%d2-%d3/%a0-%a1
    lea 16(%sp),%sp
    rts
    .balign 4
