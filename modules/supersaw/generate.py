#!/usr/bin/env python3
"""Reproduce original Fourier tables and ColdFire source; --check never writes."""
from pathlib import Path
import math
import os
import runpy
import subprocess
import sys
import tempfile
HERE = Path(__file__).resolve().parent
FLAGS = "-mcpu=54455 -O3 -ffreestanding -fno-builtin -fno-common -fno-jump-tables -fno-asynchronous-unwind-tables -fno-ident -fomit-frame-pointer -fno-zero-initialized-in-bss -Wall -Wextra -Werror".split()

def table_source():
    def array(name, rows):
        return 'static const int16_t ' + name + ' = {\n' + ',\n'.join(
            ' {' + ','.join(str(v) for v in row) + '}' for row in rows) + '\n};\n'
    banks = []
    for bank in range(8):
        harmonics = 1 << bank
        banks.append([round(-20000 * sum(math.sin(2*math.pi*n*i/2048)/n
                       for n in range(1, harmonics+1))/math.pi) for i in range(2048)])
    sine = [round(10000*math.sin(2*math.pi*i/2048)) for i in range(2048)]
    # Symmetric linear frequency spread, +/-1.5625% at maximum (~27 cents).
    ratios = [[round((1 + spread*d/(127*64)) * (1<<20))
               for spread in (-1, 1)] for d in range(128)]
    def drive(x):
        x=max(-32767,min(32767,x))
        return x-(((((x*x)>>15)*x)>>15)*10923>>15)
    drive_curve=[drive(-32768+8*i) for i in range(8193)]
    damping = []
    for res in range(128):
        b = 16351 - res*9617//128
        k = (b*b)>>14
        damping.append((k*k)>>14)
    cutoff_g = [round(math.tan(math.pi*60*250**(i/128)/44100)*16384) for i in range(128)]
    # Exact Q14 normalization for every reachable integer CUT/RES pair.
    # 32 KiB read-only: no division when a knob/envelope changes on the CPU.
    a1 = [[268435456 // (16384 + ((k*g)>>14) + ((g*g)>>14))
           for g in cutoff_g] for k in damping]
    # The filter runs before the 2x interpolator. Retain the knob law up to
    # 9 kHz, then cap it below the 11.025 kHz source Nyquist limit.
    half_g = [round(math.tan(math.pi*min(9000,60*250**(i/128))/22050)*16384) for i in range(128)]
    half_a1 = [[268435456 // (16384 + ((k*g)>>14) + ((g*g)>>14))
               for g in half_g] for k in damping]
    return ('/* Generated by generate.py. Original mathematical tables; SPDX-License-Identifier: MIT */\n'
            + array('ss_saws[8][2048]', banks)
            + 'static const int32_t ss_morph_polarity[128] = {' + ','.join(str(32768-i*65536//127) for i in range(128)) + '};\n'
            + 'static const int16_t ss_drive_curve[8193] = {' + ','.join(map(str,drive_curve)) + '};\n'
            + 'static const int16_t ss_sine[2048] = {' + ','.join(map(str,sine)) + '};\n'
            + 'static const uint32_t ss_ratios[128][2] = {\n'
            + ',\n'.join(' {' + ','.join(map(str,row)) + '}' for row in ratios) + '\n};\n'
            + 'static const int32_t ss_filter_g[128] = {' + ','.join(map(str,cutoff_g)) + '};\n'
            + 'static const int16_t ss_filter_damping[128] = {' + ','.join(map(str,damping)) + '};\n'
            + 'static const uint16_t ss_filter_a1[128][128] = {\n'
            + ',\n'.join(' {' + ','.join(map(str,row)) + '}' for row in a1) + '\n};\n'
            + 'static const int32_t ss_filter_half_g[128] = {' + ','.join(map(str,half_g)) + '};\n'
            + 'static const uint16_t ss_filter_half_a1[128][128] = {\n'
            + ',\n'.join(' {' + ','.join(map(str,row)) + '}' for row in half_a1) + '\n};\n'
            + 'static const uint16_t ss_filter_half_decay[17][128] = {\n'
            + ',\n'.join(' {' + ','.join(str(round((1-math.exp(-math.log(100)*2*n/(44100*.02*200**(i/127))))*65536)) for i in range(128)) + '}' for n in range(17)) + '\n};\n'
            + 'static const uint16_t ss_filter_decay[128] = {' + ','.join(str(round((1-math.exp(-math.log(100)/(44100*.02*200**(i/127))))*65536)) for i in range(128)) + '};\n')

def main():
    check = '--check' in sys.argv
    flags = FLAGS + (['-DSS_DIAGNOSTICS'] if os.environ.get('SS_DIAGNOSTICS') == '1' else [])
    expected = table_source()
    if check:
        assert (HERE/'tables.h').read_text() == expected, 'stale Supersaw tables'
    else:
        (HERE/'tables.h').write_text(expected)
    with tempfile.TemporaryDirectory() as temp:
        target = Path(temp)/'adapter.s'
        subprocess.run(['m68k-elf-gcc',*flags,'-S','adapter.c','-o',str(target)],cwd=HERE,check=True)
        asm = '| Generated by modules/supersaw/generate.py; edit the C sources.\n' + target.read_text()
    if check:
        assert (HERE/'adapter.s').read_text() == asm, 'stale Supersaw assembly'
        print('[ok] Supersaw tables and ColdFire source reproduce')
    else:
        (HERE/'adapter.s').write_text(asm)
if __name__ == '__main__': main()
