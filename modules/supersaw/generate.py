#!/usr/bin/env python3
"""Reproduce original Fourier tables and ColdFire source; --check never writes."""
from pathlib import Path
import math
import runpy
import subprocess
import sys
import tempfile
HERE = Path(__file__).resolve().parent
FLAGS = "-mcpu=54455 -O2 -ffreestanding -fno-builtin -fno-common -fno-jump-tables -fno-asynchronous-unwind-tables -fno-ident -fomit-frame-pointer -fno-zero-initialized-in-bss -Wall -Wextra -Werror".split()

def table_source():
    def array(name, rows):
        return 'static const int16_t ' + name + ' = {\n' + ',\n'.join(
            ' {' + ','.join(str(v) for v in row) + '}' for row in rows) + '\n};\n'
    banks = []
    for bank in range(8):
        harmonics = 1 << bank
        banks.append([round(-20000 * sum(math.sin(2*math.pi*n*i/2048)/n
                       for n in range(1, harmonics+1))/math.pi) for i in range(2048)])
    sine = [round(10000*math.sin(2*math.pi*i/2048)) for i in range(2048)]
    # Symmetric linear frequency spread, +/-1.5625% at maximum (~27 cents).
    ratios = [[round((1 + spread*d/(127*64)) * (1<<20))
               for spread in (-1, 1)] for d in range(128)]
    return ('/* Generated by generate.py. Original mathematical tables; SPDX-License-Identifier: MIT */\n'
            + array('ss_saws[8][2048]', banks)
            + 'static const int16_t ss_sine[2048] = {' + ','.join(map(str,sine)) + '};\n'
            + 'static const uint32_t ss_ratios[128][2] = {\n'
            + ',\n'.join(' {' + ','.join(map(str,row)) + '}' for row in ratios) + '\n};\n'
            + 'static const int32_t ss_filter_g[128] = {' + ','.join(str(round(math.tan(math.pi*60*250**(i/128)/44100)*16384)) for i in range(128)) + '};\n'
            + 'static const uint16_t ss_filter_decay[128] = {' + ','.join(str(round((1-math.exp(-math.log(100)/(44100*.02*200**(i/127))))*65536)) for i in range(128)) + '};\n')

def main():
    check = '--check' in sys.argv
    expected = table_source()
    if check:
        assert (HERE/'tables.h').read_text() == expected, 'stale Supersaw tables'
    else:
        (HERE/'tables.h').write_text(expected)
    with tempfile.TemporaryDirectory() as temp:
        target = Path(temp)/'adapter.s'
        subprocess.run(['m68k-elf-gcc',*FLAGS,'-S','adapter.c','-o',str(target)],cwd=HERE,check=True)
        asm = '| Generated by modules/supersaw/generate.py; edit the C sources.\n' + target.read_text()
    if check:
        assert (HERE/'adapter.s').read_text() == asm, 'stale Supersaw assembly'
        print('[ok] Supersaw tables and ColdFire source reproduce')
    else:
        (HERE/'adapter.s').write_text(asm)
if __name__ == '__main__': main()
