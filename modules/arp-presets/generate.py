#!/usr/bin/env python3
"""Keep the Linked source identical to presets.c + hooks.s (BRAIN's pattern)."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-Wall', '-Wextra', '-Werror']


def generate():
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'presets.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S',
                        'modules/arp-presets/presets.c', '-o', str(asm)], cwd=ROOT, check=True)
        return ('| Generated by modules/arp-presets/generate.py; edit presets.c / hooks.s.\n'
                + asm.read_text() + '\n' + (HERE / 'hooks.s').read_text())


if __name__ == '__main__':
    source = generate()
    dest = HERE / 'presets.s'
    if '--check' in sys.argv:
        if not dest.exists() or source != dest.read_text():
            sys.exit('ARP PRESETS source is stale: run modules/arp-presets/generate.py')
        print('ARP PRESETS ColdFire source matches presets.c and hooks.s')
    else:
        dest.write_text(source)
