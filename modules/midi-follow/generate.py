#!/usr/bin/env python3
"""Generate Follow's register calculation using the Harmony compiler pattern."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=54455', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-jump-tables', '-fno-asynchronous-unwind-tables', '-fno-ident',
         '-fomit-frame-pointer', '-Wall', '-Wextra', '-Wmissing-prototypes',
         '-Wstrict-prototypes', '-Werror']

def main():
    with tempfile.TemporaryDirectory(prefix='follow-generate-') as tmp:
        dest = pathlib.Path(tmp)/'gravity.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', '-o', str(dest), 'gravity.c'],
                       cwd=HERE, check=True)
        body = '| Generated by generate.py; edit gravity.c and gravity.h.\n'+dest.read_text()
    target = HERE/'gravity.s'
    if '--check' in sys.argv:
        if not target.exists() or target.read_text()!=body:
            raise SystemExit('stale generated Follow assembly')
        print('Follow generated assembly matches')
    else:
        target.write_text(body)

if __name__ == '__main__':
    main()
