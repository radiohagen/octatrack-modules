#!/usr/bin/env python3
"""Generate the ColdFire adapter, or verify that its checked-in source is current."""
from pathlib import Path
import subprocess
import sys
import tempfile
HERE=Path(__file__).resolve().parent
FLAGS="-mcpu=54455 -O2 -ffreestanding -fno-builtin -fno-common -fno-jump-tables -fno-asynchronous-unwind-tables -fno-ident -fomit-frame-pointer -fno-zero-initialized-in-bss -Wall -Wextra -Werror".split()
def main():
    with tempfile.TemporaryDirectory() as tmp:
        target=Path(tmp)/"adapter.s"
        subprocess.run(["m68k-elf-gcc",*FLAGS,"-S","adapter.c","-o",str(target)],cwd=HERE,check=True)
        body="| Generated by modules/sophie/generate.py; edit adapter.c.\n"+target.read_text()
    dest=HERE/"adapter.s"
    if "--check" in sys.argv:
        if not dest.exists() or dest.read_text()!=body:raise SystemExit("stale Sophie adapter.s")
        print("[ok] Sophie generated source")
    else:dest.write_text(body)
if __name__=="__main__":main()
