#!/usr/bin/env python3
"""Generate the independent Euclid LFO's ColdFire unit; --check detects drift."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-Wall', '-Wextra', '-Werror']

def generate(sidecar=False):
    with tempfile.TemporaryDirectory(prefix='euclid-lfo-') as td:
        asm = pathlib.Path(td) / 'control.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, *(['-DEUL_SIDECAR_ONLY=1'] if sidecar else []), '-S',
                        'modules/euclid-lfo/control.c', '-o', str(asm)], cwd=ROOT, check=True)
        return ('| Generated by modules/euclid-lfo/generate_control.py.\n'
                + asm.read_text() + '\n' + (HERE / 'hooks.s').read_text())

if __name__ == '__main__':
    for sidecar, name in ((False, 'control.s'), (True, 'control-sidecar.s')):
        source = generate(sidecar)
        dest = HERE / name
        if '--check' in sys.argv:
            if not dest.exists() or source != dest.read_text():
                sys.exit(f'Euclid LFO {name} is stale: run generate_control.py')
        else:
            dest.write_text(source)
    if '--check' in sys.argv:
        print('Euclid LFO SRAM and sidecar generated sources match')
