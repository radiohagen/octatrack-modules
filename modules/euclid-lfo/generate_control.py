#!/usr/bin/env python3
"""Generate the independent Euclid LFO's ColdFire unit; --check detects drift."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-fno-zero-initialized-in-bss',
         '-Wall', '-Wextra', '-Werror']

def generate(sidecar=False):
    with tempfile.TemporaryDirectory(prefix='euclid-lfo-') as td:
        asm = pathlib.Path(td) / 'control.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, *(['-DEUL_SIDECAR_ONLY=1'] if sidecar else []), '-S',
                        'modules/euclid-lfo/control.c', '-o', str(asm)], cwd=ROOT, check=True)
        source = ('| Generated by modules/euclid-lfo/generate_control.py.\n'
                + asm.read_text() + '\n' + (HERE / 'hooks.s').read_text())
        # The DRAM loader copies .data but does not clear .bss/COMMON.
        # Even an explicit C '= 0' otherwise leaves guards such as
        # rate_writing at whatever power-up or a previous remix left there.
        asm.write_text(source)
        obj = pathlib.Path(td) / 'control.o'
        subprocess.run(['m68k-elf-as', '-mcpu=5475', '-o', str(obj), str(asm)], check=True)
        symbols = subprocess.check_output(['m68k-elf-nm', str(obj)], text=True)
        uninitialized = [line for line in symbols.splitlines()
                         if len(fields := line.split()) == 3 and fields[1] in 'BbCc']
        if uninitialized:
            raise RuntimeError('Euclid state outside loader-initialized data: ' + ', '.join(uninitialized))
        return source

if __name__ == '__main__':
    for sidecar, name in ((False, 'control.s'), (True, 'control-sidecar.s')):
        source = generate(sidecar)
        dest = HERE / name
        if '--check' in sys.argv:
            if not dest.exists() or source != dest.read_text():
                sys.exit(f'Euclid LFO {name} is stale: run generate_control.py')
        else:
            dest.write_text(source)
    if '--check' in sys.argv:
        print('Euclid LFO SRAM and sidecar generated sources match')
