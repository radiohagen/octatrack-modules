#!/usr/bin/env python3
"""Existing freestanding C-to-ColdFire assembly pattern; no runtime compiler."""
import pathlib
import subprocess
import sys
import tempfile

HERE=pathlib.Path(__file__).resolve().parent
FLAGS=['-mcpu=54455','-O2','-ffreestanding','-fno-builtin','-fno-common',
       '-fno-jump-tables','-fno-asynchronous-unwind-tables','-fno-ident',
       '-fomit-frame-pointer','-Wall','-Wextra','-Wmissing-prototypes',
       '-Wstrict-prototypes','-Werror']
with tempfile.TemporaryDirectory(prefix='loopback-translation-') as tmp:
    for unit in ('translation','translation-files'):
        output=pathlib.Path(tmp)/(unit+'.s')
        subprocess.run(['m68k-elf-gcc',*FLAGS,'-S','-o',str(output),unit+'.c'],
                       cwd=HERE,check=True)
        body=f'| Generated by generate_translation.py; edit {unit}.c / translation.h.\n'+output.read_text()
        target=HERE/(unit+'.s')
        if '--check' in sys.argv:
            if not target.exists() or target.read_text()!=body:
                raise SystemExit('stale '+unit+' assembly')
            print('[ok] generated '+unit+' assembly matches C source')
        else:
            target.write_text(body)
