#!/usr/bin/env python3
"""Generate ColdFire pool implementation; --check refuses drift."""
import pathlib, subprocess, sys, tempfile
HERE = pathlib.Path(__file__).resolve().parent
with tempfile.TemporaryDirectory(prefix='midi-sram-') as td:
    out = pathlib.Path(td)/'pool.s'
    subprocess.run(['m68k-elf-gcc', '-mcpu=54455', '-O2', '-ffreestanding',
        '-fno-builtin', '-fno-common', '-fno-jump-tables',
        '-fno-asynchronous-unwind-tables', '-fno-ident', '-fomit-frame-pointer',
        '-Wall', '-Wextra', '-Werror', '-S', 'pool.c', '-o', str(out)], cwd=HERE, check=True)
    assert '*8)' not in out.read_text(), 'hardware-unsafe ColdFire addressing'
    body = '| Generated by generate.py; edit pool.c.\n' + out.read_text()
    if '--check' in sys.argv:
        assert (HERE/'pool.s').read_text() == body, 'stale pool.s'
    else:
        (HERE/'pool.s').write_text(body)
